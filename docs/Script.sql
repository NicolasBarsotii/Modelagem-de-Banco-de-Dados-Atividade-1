-- ==========================================================
-- 5. SELECT COM JOIN (Consultas de Junção)
-- ==========================================================

-- SELECT 1: Ver todos os itens dos pedidos, seus produtos e preços
SELECT P.CD_PEDIDO, PR.NM_PRODUTO, I.QT_ITEM, I.VL_UNITARIO, I.VL_SUBTOTAL
FROM PEDIDO P
JOIN ITEM_PEDIDO I ON P.CD_PEDIDO = I.CD_PEDIDO
JOIN PRODUTO PR ON I.CD_PRODUTO = PR.CD_PRODUTO;

-- SELECT 2: Ver os pagamentos e o nome do funcionário que registrou o pedido
SELECT P.CD_PEDIDO, F.NM_FUNCIONARIO, PAG.TP_FORMA_PAG, PAG.VL_PAGAMENTO
FROM PEDIDO P
JOIN FUNCIONARIO F ON P.CD_FUNCIONARIO = F.CD_FUNCIONARIO
JOIN PAGAMENTO PAG ON P.CD_PEDIDO = PAG.CD_PEDIDO;

-- ==========================================================
-- 6. CONSULTAS GERENCIAIS (G01 a G05)
-- ==========================================================

-- G01 — Quais produtos estão abaixo do estoque mínimo hoje?
-- Atende: P1 (ruptura de estoque de bebidas) e KPI02
SELECT NM_PRODUTO, QT_ESTOQUE, QT_ESTOQUE_MIN 
FROM PRODUTO 
WHERE QT_ESTOQUE < QT_ESTOQUE_MIN;

-- G02 — Qual o faturamento total por forma de pagamento?
-- Atende: P4 (fechamento de caixa) e KPI05 (mix de pagamento)
SELECT TP_FORMA_PAG, SUM(VL_PAGAMENTO) AS Total_Faturado
FROM PAGAMENTO
WHERE TP_STATUS_PAG = 'Pago'
GROUP BY TP_FORMA_PAG;

-- G03 — Qual o prejuízo total com perdas de perecíveis?
-- Atende: P3 (perdas de perecíveis) e KPI04 (taxa de perdas)
SELECT PR.NM_PRODUTO, SUM(M.QT_MOVIMENTACAO) AS Qtd_Perdida, 
       (SUM(M.QT_MOVIMENTACAO) * PR.VL_VENDA) AS Prejuizo_Estimado
FROM ESTOQUE_MOVIMENTACAO M
JOIN PRODUTO PR ON M.CD_PRODUTO = PR.CD_PRODUTO
WHERE M.TP_MOVIMENTACAO = 'Perda'
GROUP BY PR.CD_PRODUTO, PR.NM_PRODUTO, PR.VL_VENDA;

-- G04 — Qual o ticket médio por canal de atendimento?
-- Atende: KPI01 (Ticket Médio)
SELECT TP_CANAL, AVG(VL_TOTAL) AS Ticket_Medio
FROM PEDIDO
WHERE TP_STATUS != 'Cancelado'
GROUP BY TP_CANAL;

-- G05 — Qual o volume de pedidos por status?
-- Atende: P2 (desorganização de pedidos)
SELECT TP_STATUS, COUNT(*) AS Quantidade_Pedidos
FROM PEDIDO
GROUP BY TP_STATUS;

-- ==========================================================
-- 7. CONSULTAS DE AUDITORIA (A01 a A03)
-- ==========================================================

-- A01 — Existe pedido registrado sem nenhum item?
-- Verifica: RN04 (Todo pedido deve ter pelo menos 1 item)
SELECT P.CD_PEDIDO, P.DT_PEDIDO
FROM PEDIDO P
LEFT JOIN ITEM_PEDIDO I ON P.CD_PEDIDO = I.CD_PEDIDO
WHERE I.CD_ITEM IS NULL;

-- A02 — Existe movimentação de 'Entrada' sem fornecedor associado?
-- Verifica: Integridade da regra de negócio de compras
SELECT CD_MOVIMENTACAO, TP_MOVIMENTACAO
FROM ESTOQUE_MOVIMENTACAO
WHERE TP_MOVIMENTACAO = 'Entrada' AND CD_FORNECEDOR IS NULL;

-- A03 — Existe pagamento com valor negativo ou zero que foi marcado como 'Pago'?
-- Verifica: Integridade financeira
SELECT CD_PAGAMENTO, VL_PAGAMENTO, TP_STATUS_PAG
FROM PAGAMENTO
WHERE VL_PAGAMENTO <= 0 AND TP_STATUS_PAG = 'Pago';