-- 1. CREATE DATABASE
DROP DATABASE IF EXISTS maxfood;
CREATE DATABASE maxfood CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE maxfood;

-- 2. CREATE TABLE (Estrutura)

-- Tabelas Independentes
CREATE TABLE FUNCIONARIO (
    CD_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NM_FUNCIONARIO VARCHAR(60) NOT NULL,
    TP_CARGO ENUM('Atendimento', 'Cozinha', 'Gerente') NOT NULL,
    NR_TELEFONE VARCHAR(15),
    NM_EMAIL VARCHAR(80),
    IN_ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE FORNECEDOR (
    CD_FORNECEDOR INT AUTO_INCREMENT PRIMARY KEY,
    NM_FORNECEDOR VARCHAR(80) NOT NULL,
    NR_CNPJ VARCHAR(18) UNIQUE,
    NR_TELEFONE VARCHAR(15) NOT NULL,
    NM_EMAIL VARCHAR(80),
    DS_ENDERECO VARCHAR(120),
    NM_CONTATO VARCHAR(60),
    IN_ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE PRODUTO (
    CD_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
    NM_PRODUTO VARCHAR(60) NOT NULL,
    DS_PRODUTO VARCHAR(120),
    TP_CATEGORIA VARCHAR(30) NOT NULL,
    VL_VENDA DECIMAL(7,2) NOT NULL CHECK (VL_VENDA >= 0),
    VL_COMBO DECIMAL(7,2) CHECK (VL_COMBO >= 0),
    TP_UNIDADE VARCHAR(10) NOT NULL,
    TP_ESTOQUE ENUM('Interno', 'Amostra') NOT NULL,
    QT_ESTOQUE INT NOT NULL DEFAULT 0 CHECK (QT_ESTOQUE >= 0),
    QT_ESTOQUE_MIN INT NOT NULL DEFAULT 0 CHECK (QT_ESTOQUE_MIN >= 0),
    IN_PERECIVEL BOOLEAN DEFAULT FALSE,
    IN_PERMITE_ACOMP BOOLEAN DEFAULT FALSE,
    IN_PERMITE_COB BOOLEAN DEFAULT FALSE,
    IN_ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE ACOMPANHAMENTO (
    CD_ACOMPANHAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    NM_ACOMPANHAMENTO VARCHAR(40) NOT NULL,
    TP_ACOMPANHAMENTO ENUM('Acompanhamento', 'Cobertura') NOT NULL,
    VL_ADICIONAL DECIMAL(6,2) DEFAULT 0.00 CHECK (VL_ADICIONAL >= 0)
);

CREATE TABLE FECHAMENTO_CAIXA (
    CD_FECHAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    DT_FECHAMENTO DATE NOT NULL,
    VL_TOTAL_DINHEIRO DECIMAL(8,2) DEFAULT 0.00,
    VL_TOTAL_CARTAO DECIMAL(8,2) DEFAULT 0.00,
    VL_TOTAL_PIX DECIMAL(8,2) DEFAULT 0.00,
    VL_TOTAL_GERAL DECIMAL(8,2) DEFAULT 0.00
);

-- Tabelas Dependentes (Com FKs)
CREATE TABLE PEDIDO_COMPRA (
    CD_PEDIDO_COMPRA INT AUTO_INCREMENT PRIMARY KEY,
    CD_FORNECEDOR INT NOT NULL,
    DT_COMPRA DATETIME DEFAULT CURRENT_TIMESTAMP,
    TP_STATUS ENUM('Pendente', 'Recebido', 'Cancelado') DEFAULT 'Pendente',
    FOREIGN KEY (CD_FORNECEDOR) REFERENCES FORNECEDOR(CD_FORNECEDOR) ON DELETE RESTRICT
);

CREATE TABLE ITEM_COMPRA (
    CD_ITEM_COMPRA INT AUTO_INCREMENT PRIMARY KEY,
    CD_PEDIDO_COMPRA INT NOT NULL,
    CD_PRODUTO INT NOT NULL,
    QT_COMPRA INT NOT NULL CHECK (QT_COMPRA > 0),
    VL_UNITARIO DECIMAL(7,2) NOT NULL CHECK (VL_UNITARIO >= 0),
    FOREIGN KEY (CD_PEDIDO_COMPRA) REFERENCES PEDIDO_COMPRA(CD_PEDIDO_COMPRA) ON DELETE CASCADE,
    FOREIGN KEY (CD_PRODUTO) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE RESTRICT
);

CREATE TABLE ESTOQUE_MOVIMENTACAO (
    CD_MOVIMENTACAO INT AUTO_INCREMENT PRIMARY KEY,
    CD_PRODUTO INT NOT NULL,
    CD_FORNECEDOR INT NULL, -- Permitido NULL para saídas e ajustes
    TP_MOVIMENTACAO ENUM('Entrada', 'Saída', 'Ajuste', 'Perda') NOT NULL,
    QT_MOVIMENTACAO INT NOT NULL CHECK (QT_MOVIMENTACAO > 0),
    DT_MOVIMENTACAO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DS_OBSERVACAO VARCHAR(120),
    FOREIGN KEY (CD_PRODUTO) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE RESTRICT,
    FOREIGN KEY (CD_FORNECEDOR) REFERENCES FORNECEDOR(CD_FORNECEDOR) ON DELETE SET NULL
);

CREATE TABLE PEDIDO (
    CD_PEDIDO INT AUTO_INCREMENT PRIMARY KEY,
    CD_FUNCIONARIO INT NOT NULL,
    DT_PEDIDO DATETIME DEFAULT CURRENT_TIMESTAMP,
    TP_CANAL ENUM('Balcão', 'WhatsApp', 'Telefone') NOT NULL,
    TP_STATUS ENUM('Aberto', 'Em preparo', 'Entregue', 'Cancelado') DEFAULT 'Aberto',
    NM_CLIENTE VARCHAR(60),
    NR_TELEFONE_CLI VARCHAR(15),
    VL_TOTAL DECIMAL(8,2) DEFAULT 0.00 CHECK (VL_TOTAL >= 0),
    VL_DESCONTO DECIMAL(7,2) DEFAULT 0.00 CHECK (VL_DESCONTO >= 0),
    DS_MOTIVO_DESC VARCHAR(60),
    DS_OBSERVACAO VARCHAR(120),
    FOREIGN KEY (CD_FUNCIONARIO) REFERENCES FUNCIONARIO(CD_FUNCIONARIO) ON DELETE RESTRICT
);

CREATE TABLE ITEM_PEDIDO (
    CD_ITEM INT AUTO_INCREMENT PRIMARY KEY,
    CD_PEDIDO INT NOT NULL,
    CD_PRODUTO INT NOT NULL,
    QT_ITEM INT NOT NULL CHECK (QT_ITEM > 0),
    VL_UNITARIO DECIMAL(7,2) NOT NULL CHECK (VL_UNITARIO >= 0),
    VL_SUBTOTAL DECIMAL(8,2) NOT NULL CHECK (VL_SUBTOTAL >= 0),
    DS_OBSERVACAO VARCHAR(120),
    FOREIGN KEY (CD_PEDIDO) REFERENCES PEDIDO(CD_PEDIDO) ON DELETE CASCADE,
    FOREIGN KEY (CD_PRODUTO) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE RESTRICT
);

CREATE TABLE PAGAMENTO (
    CD_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    CD_PEDIDO INT NOT NULL,
    TP_FORMA_PAG ENUM('Débito', 'Crédito', 'Pix', 'Dinheiro') NOT NULL,
    VL_PAGAMENTO DECIMAL(8,2) NOT NULL CHECK (VL_PAGAMENTO > 0),
    DT_PAGAMENTO DATETIME DEFAULT CURRENT_TIMESTAMP,
    TP_STATUS_PAG ENUM('Pendente', 'Pago', 'Cancelado') DEFAULT 'Pago',
    FOREIGN KEY (CD_PEDIDO) REFERENCES PEDIDO(CD_PEDIDO) ON DELETE RESTRICT
);

CREATE TABLE PRATO_DO_DIA (
    CD_PRATO_DIA INT AUTO_INCREMENT PRIMARY KEY,
    CD_PRODUTO INT NOT NULL,
    DT_OFERTA DATE NOT NULL,
    VL_PROMOCIONAL DECIMAL(7,2) NOT NULL CHECK (VL_PROMOCIONAL >= 0),
    DS_DESCRICAO VARCHAR(120),
    IN_ATIVO BOOLEAN DEFAULT TRUE,
    FOREIGN KEY (CD_PRODUTO) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE CASCADE
);

CREATE TABLE COMBO_ITEM (
    CD_COMBO_ITEM INT AUTO_INCREMENT PRIMARY KEY,
    CD_PRODUTO_COMBO INT NOT NULL,
    CD_PRODUTO_ITEM INT NOT NULL,
    QT_ITEM INT NOT NULL CHECK (QT_ITEM > 0),
    FOREIGN KEY (CD_PRODUTO_COMBO) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE CASCADE,
    FOREIGN KEY (CD_PRODUTO_ITEM) REFERENCES PRODUTO(CD_PRODUTO) ON DELETE RESTRICT
);

CREATE TABLE ITEM_PEDIDO_ACOMPANHAMENTO (
    CD_ITEM INT NOT NULL,
    CD_ACOMPANHAMENTO INT NOT NULL,
    QT_ESCOLHA INT NOT NULL CHECK (QT_ESCOLHA > 0),
    PRIMARY KEY (CD_ITEM, CD_ACOMPANHAMENTO),
    FOREIGN KEY (CD_ITEM) REFERENCES ITEM_PEDIDO(CD_ITEM) ON DELETE CASCADE,
    FOREIGN KEY (CD_ACOMPANHAMENTO) REFERENCES ACOMPANHAMENTO(CD_ACOMPANHAMENTO) ON DELETE RESTRICT
);

